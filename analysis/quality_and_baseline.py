"""Data-quality checks and first baselines for the weekly Glasgow A&E dataset.

Run after build_dataset.py:  python3 -I quality_and_baseline.py
Writes data_quality.md next to this script.
Needs only numpy + stdlib.
"""
import csv
import datetime as dt
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SITES = ["QEUH", "GRI", "RHC"]
FEATURES = ["temp_mean", "temp_max", "temp_min",
            "humidity_mean", "precip_sum", "pm2_5_mean", "pm10_mean"]
TEST_START = dt.date(2024, 1, 1)  # chronological split: train < 2024, test >= 2024


def load():
    rows = list(csv.DictReader(open(os.path.join(HERE, "data", "weekly_dataset.csv"))))
    out = []
    for r in rows:
        d = {"week_ending": dt.date.fromisoformat(r["week_ending"])}
        for k, v in r.items():
            if k != "week_ending":
                d[k] = float(v) if v not in ("", "None") else None
        out.append(d)
    return out


def mae(a, b):
    return float(np.mean(np.abs(np.array(a) - np.array(b))))


def mape(a, b):
    a, b = np.array(a, float), np.array(b, float)
    return float(np.mean(np.abs(a - b) / a) * 100)


def main():
    rows = load()
    n = len(rows)
    L = []
    L.append("# Data quality and baseline results (preliminary work)\n")
    L.append(f"Generated by `quality_and_baseline.py` from `data/weekly_dataset.csv`.\n")
    L.append("## 1. Coverage\n")
    L.append(f"- Weeks: **{n}**, {rows[0]['week_ending']} to {rows[-1]['week_ending']}")
    gaps = [(a["week_ending"], b["week_ending"]) for a, b in zip(rows, rows[1:])
            if (b["week_ending"] - a["week_ending"]).days != 7]
    L.append(f"- Gaps in the weekly sequence: **{len(gaps)}** {gaps if gaps else ''}")
    L.append("- Missing values per column:")
    for k in FEATURES + [f"att_{s}" for s in SITES]:
        miss = sum(r[k] is None for r in rows)
        L.append(f"  - `{k}`: {miss}")

    L.append("\n## 2. Attendance by site (weekly)\n")
    L.append("| Site | Mean | Min | Max | Weeks < 60% of median |")
    L.append("|---|---|---|---|---|")
    low = {}
    for s in SITES:
        v = np.array([r[f"att_{s}"] for r in rows if r[f"att_{s}"] is not None])
        med = np.median(v)
        low[s] = [(r["week_ending"].isoformat(), int(r[f"att_{s}"])) for r in rows
                  if r[f"att_{s}"] is not None and r[f"att_{s}"] < 0.6 * med]
        L.append(f"| {s} | {v.mean():.0f} | {v.min():.0f} | {v.max():.0f} | {len(low[s])} |")
    L.append("\nFlag rule: a week is flagged if attendance is below 60% of the site's median. "
             "Flagged weeks are shown as contiguous runs so they can be checked against known events "
             "(site changes noted by PHS, the 2020 pandemic) before modelling. **Causes not yet verified:**")
    for s in SITES:
        runs, cur = [], []
        wk = [r["week_ending"] for r in rows]
        flagged = {dt.date.fromisoformat(d) for d, _ in low[s]}
        for w in wk:
            if w in flagged:
                if cur and (w - cur[-1]).days == 7:
                    cur.append(w)
                else:
                    if cur: runs.append(cur)
                    cur = [w]
        if cur: runs.append(cur)
        if runs:
            L.append(f"- {s}: " + "; ".join(f"{r[0]} to {r[-1]} ({len(r)} wk)" if len(r) > 1 else f"{r[0]} (1 wk)" for r in runs))

    L.append("\n## 3. How hot does Glasgow get? (daily weather, same period)\n")
    w = json.load(open(os.path.join(HERE, "data", "raw_weather_daily.json")))
    mx = [x for x in w["temperature_2m_max"] if x is not None]
    yrs = len({t[:4] for t in w["time"]})
    L.append("Weather is ERA5-Land reanalysis (~11 km grid) via Open-Meteo, NOT station records. "
             "Reanalysis smooths extremes, so station maxima can be higher; spot-check against Met Office station data.\n")
    L.append(f"- Days: {len(mx)} (~{yrs} calendar years). Hottest day: **{max(mx):.1f} C**")
    for thr in (20, 25, 27, 30):
        L.append(f"- Days with Tmax >= {thr} C: **{sum(x >= thr for x in mx)}**")

    L.append("\n## 4. Raw association between weekly mean temperature and attendance\n")
    L.append("Pearson r, whole period, **before removing seasonality or lockdown weeks** "
             "(descriptive only, not a result):\n")
    L.append("| Site | r (temp_mean) | r (pm2_5_mean) | r (humidity_mean) |")
    L.append("|---|---|---|---|")
    for s in SITES:
        ok = [r for r in rows if r[f"att_{s}"] is not None and all(r[f] is not None for f in FEATURES)]
        y = np.array([r[f"att_{s}"] for r in ok])
        cs = [np.corrcoef([r[f] for r in ok], y)[0, 1] for f in ("temp_mean", "pm2_5_mean", "humidity_mean")]
        L.append(f"| {s} | {cs[0]:+.2f} | {cs[1]:+.2f} | {cs[2]:+.2f} |")

    L.append("\n## 5. Baselines (chronological split)\n")
    L.append(f"Train: before {TEST_START}. Test: {TEST_START} onwards. "
             "Seasonal naive = same week one year earlier (t-52). Last-week naive = t-1.\n")
    L.append("| Site | Test weeks | Seasonal naive MAE | MAPE | Last-week MAE | MAPE |")
    L.append("|---|---|---|---|---|---|")
    for s in SITES:
        k = f"att_{s}"
        ys = [r[k] for r in rows]
        idx = [i for i, r in enumerate(rows)
               if r["week_ending"] >= TEST_START and i >= 52 and ys[i] is not None
               and ys[i - 52] is not None and ys[i - 1] is not None]
        y = [ys[i] for i in idx]
        s52 = [ys[i - 52] for i in idx]
        s1 = [ys[i - 1] for i in idx]
        L.append(f"| {s} | {len(idx)} | {mae(y, s52):.0f} | {mape(y, s52):.1f}% | "
                 f"{mae(y, s1):.0f} | {mape(y, s1):.1f}% |")
    L.append("\nThe proposal's target (beat the baseline error by at least 15%) "
             "should be confirmed or revised against these numbers.\n")
    L.append("## 6. Caveats\n")
    L.append("- Air quality is CAMS **modelled** output at a coarse grid, not monitor measurements.")
    L.append("- One weather point (city centre) is used for both hospitals.")
    L.append("- Counts are all attendances, not diagnoses.")
    L.append("- No machine-learning model has been trained yet; only baselines.")
    path = os.path.join(HERE, "data_quality.md")
    open(path, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
