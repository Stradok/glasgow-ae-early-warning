"""Turn the CSV outputs into readable markdown tables (results/results_tables.md).

    cd analysis && .venv/bin/python -I make_tables.py
Every number in the write-up should be copied from this file, not typed from memory.
"""
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
R = os.path.join(HERE, "results")
SITES = ["QEUH", "GRI", "RHC"]
NAME = {"B1": "B1 seasonal naive", "B2": "B2 last week", "M1": "M1 GAM, no weather", "M2": "M2 GAM + weather",
        "M3": "M3 XGBoost, all features", "M3a": "M3a XGBoost, no weather"}


def md(df, floatfmt="{:.1f}"):
    cols = list(df.columns)
    out = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(floatfmt.format(v) if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out)


def pfmt(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def main():
    m = pd.read_csv(os.path.join(R, "metrics.csv"))
    dm = pd.read_csv(os.path.join(R, "dm_tests.csv"))
    L = ["# Results tables (generated by make_tables.py)\n",
         "Test: 146 weeks, 7 Jan 2024 to 18 Oct 2026, rolling origin, expanding window, weekly re-fit. "
         "MAE in attendances per week. Skill = 1 - MAE/MAE(B2 last week).\n"]

    L.append("## T1. One week ahead, all weeks used in training (primary result)\n")
    for metric, title in (("MAE", "MAE"), ("MAPE", "MAPE %"), ("skill_vs_B2", "Skill vs last week (%)")):
        t = m[(m.h == 1) & (m.variant == "all")].pivot(index="model", columns="site", values=metric)[SITES]
        if metric == "skill_vs_B2":
            t = t * 100
        t = t.loc[["B1", "B2", "M1", "M2", "M3", "M3a"]]
        t.index = [NAME[i] for i in t.index]
        L.append(f"**{title}**\n")
        L.append(md(t.reset_index().rename(columns={"index": "Model"}), "{:.1f}") + "\n")

    L.append("## T2. Hypothesis tests, one week ahead (Diebold-Mariano, absolute-error loss, 5% level)\n")
    L.append("Negative difference = first model has the smaller error. Holm correction is across QEUH and GRI "
             "(RHC is exploratory, no correction).\n")
    rows = []
    lab = {("M2", "M1"): "H1: M2 vs M1 (weather adds value?)", ("M2", "B2"): "H2: M2 vs B2 last week",
           ("M2", "B1"): "H2: M2 vs B1 seasonal", ("M1", "B2"): "M1 vs B2 (no weather vs last week)",
           ("M3", "M2"): "M3 vs M2", ("M3", "M3a"): "M3 vs M3a (XGBoost with vs without weather)"}
    for (a, b), name in lab.items():
        for s in SITES:
            r = dm[(dm.h == 1) & (dm.variant == "all") & (dm.model_a == a) & (dm.model_b == b) & (dm.site == s)].iloc[0]
            rows.append({"Comparison": name, "Site": s, "MAE diff": f"{r.mean_abs_err_diff:+.1f}",
                         "DM stat": f"{r.dm_stat:+.2f}", "p": pfmt(r.p_raw),
                         "p (Holm)": pfmt(r.p_holm) if pd.notna(r.p_holm) else "n/a"})
    L.append(md(pd.DataFrame(rows)) + "\n")

    L.append("## T3. Longer horizons (MAE)\n")
    t = m[(m.variant == "all") & m.model.isin(["B2", "M1", "M2", "M3"])].pivot_table(index=["h", "model"], columns="site", values="MAE")[SITES]
    t = t.reset_index()
    t["model"] = t["model"].map(NAME)
    L.append(md(t.rename(columns={"h": "Weeks ahead", "model": "Model"})) + "\n")
    L.append("DM tests M2 vs M1 at 2 and 4 weeks ahead:\n")
    rows = []
    for h in (2, 4):
        for s in SITES:
            r = dm[(dm.h == h) & (dm.variant == "all") & (dm.model_a == "M2") & (dm.model_b == "M1") & (dm.site == s)].iloc[0]
            rows.append({"Weeks ahead": h, "Site": s, "MAE diff": f"{r.mean_abs_err_diff:+.1f}", "p": pfmt(r.p_raw),
                         "p (Holm)": pfmt(r.p_holm) if pd.notna(r.p_holm) else "n/a"})
    L.append(md(pd.DataFrame(rows)) + "\n")

    L.append("## T4. Sensitivity to flagged weeks (one week ahead; training with vs without flagged weeks)\n")
    t = m[(m.h == 1) & m.model.isin(["M1", "M2", "M3"])].pivot_table(index=["variant", "model"], columns="site", values="MAE")[SITES].reset_index()
    t["variant"] = t["variant"].map({"all": "all weeks", "noflag": "flagged weeks excluded"})
    t["model"] = t["model"].map(NAME)
    L.append(md(t.rename(columns={"variant": "Training data", "model": "Model"})) + "\n")
    L.append("The 146 test weeks contain no flagged week, so only the training data differ.\n")

    L.append("## T5. Which weather matters (ablation) and placebo (MAE, one week ahead)\n")
    rb = pd.read_csv(os.path.join(R, "robustness_metrics.csv"))
    rd = pd.read_csv(os.path.join(R, "robustness_dm.csv"))
    order = ["B2", "M1", "M2_placebo", "M2a", "M2w", "M2t", "M2"]
    lab2 = {"B2": "B2 last week", "M1": "M1 no weather", "M2_placebo": "M2 fed last year's weather (placebo)",
            "M2a": "M1 + air quality only", "M2w": "M1 + humidity and rain only", "M2t": "M1 + temperature only",
            "M2": "M2 all weather"}
    t = rb.pivot(index="model", columns="site", values="MAE")[SITES].loc[order]
    t.index = [lab2[i] for i in t.index]
    L.append(md(t.reset_index().rename(columns={"index": "Model"})) + "\n")
    rows = []
    for _, r in rd.iterrows():
        rows.append({"Comparison": f"{lab2.get(r.model_a, r.model_a)} vs {lab2.get(r.model_b, r.model_b)}", "Site": r.site,
                     "MAE diff": f"{r.mean_abs_err_diff:+.1f}", "p": pfmt(r.p_raw),
                     "p (Holm)": pfmt(r.p_holm) if pd.notna(r.p_holm) else "n/a"})
    L.append(md(pd.DataFrame(rows)) + "\n")

    L.append("## T6. Alert evaluation (one week ahead; high = above the 90th percentile of the previous 52 weeks)\n")
    al = pd.read_csv(os.path.join(R, "alerts.csv"))
    al = al[al.model.isin(["B2", "M1", "M2", "M3"])].copy()
    al["model"] = al["model"].map(NAME)
    al["Precision (95% CI)"] = [f"{r.precision:.2f} ({r.precision_lo:.2f}-{r.precision_hi:.2f})" for r in al.itertuples()]
    al["Recall (95% CI)"] = [f"{r.recall:.2f} ({r.recall_lo:.2f}-{r.recall_hi:.2f})" for r in al.itertuples()]
    al = al[["site", "model", "actual_high", "alerts", "TP", "FP", "FN", "Precision (95% CI)", "Recall (95% CI)", "false_alarms_per_month"]]
    al.columns = ["Site", "Model", "High weeks", "Alerts", "TP", "FP", "FN", "Precision (95% CI)", "Recall (95% CI)", "False alarms / month"]
    L.append(md(al, "{:.2f}") + "\n")
    L.append("Intervals are Wilson 95% intervals on small counts (11 to 26 alerts per row): treat them as very wide.\n")

    ep = os.path.join(R, "alerts_extended.csv")
    if os.path.exists(ep):
        L.append("## T6b. Alerts for the prototype's model (M2t), with forecast weather, and the medium tier\n")
        L.append("Same rule as T6, one week ahead. high = above the 90th percentile of the previous 52 weeks; medium = above the 75th "
                 "(\"medium or above\"). observed = observed target-week weather (146 weeks); forecast = archived ECMWF forecasts (135 weeks). "
                 "Base rate = share of weeks that were positive (the precision a random alert would have).\n")
        ae = pd.read_csv(ep)
        ae = ae[ae.model.isin(["B2", "M2t"])].copy()
        ae["Precision (95% CI)"] = [f"{r.precision:.2f} ({r.precision_lo:.2f}-{r.precision_hi:.2f})" for r in ae.itertuples()]
        ae["Recall (95% CI)"] = [f"{r.recall:.2f} ({r.recall_lo:.2f}-{r.recall_hi:.2f})" for r in ae.itertuples()]
        ae["base_rate"] = ae["base_rate"] * 100
        ae = ae[["source", "tier", "site", "model", "weeks", "actual_pos", "base_rate", "alerts", "Precision (95% CI)",
                 "Recall (95% CI)", "false_alarms_per_month"]]
        ae.columns = ["Weather", "Tier", "Site", "Model", "Weeks", "Positive weeks", "Base rate %", "Alerts",
                      "Precision (95% CI)", "Recall (95% CI)", "False alarms / month"]
        L.append(md(ae, "{:.2f}") + "\n")

    hp = os.path.join(R, "dm_hac.csv")
    if os.path.exists(hp):
        L.append("## T8. Sensitivity: Diebold-Mariano with a Newey-West (HAC) variance (one week ahead)\n")
        L.append("The plain test (T2) ignores autocorrelation of the loss differences. Newey-West with 3 and 8 lags as a check; Holm across QEUH and GRI.\n")
        hc = pd.read_csv(hp)
        rows = []
        for r in hc.itertuples():
            rows.append({"Comparison": f"{r.model_a} vs {r.model_b}", "Site": r.site, "Lags": r.lags, "MAE diff": f"{r.mean_abs_err_diff:+.1f}",
                         "p": pfmt(r.p_raw), "p (Holm)": pfmt(r.p_holm) if pd.notna(r.p_holm) else "n/a"})
        L.append(md(pd.DataFrame(rows)) + "\n")
    tp = os.path.join(R, "temperature_effect.csv")
    if os.path.exists(tp):
        L.append("## T9. Size of the temperature association (fitted M2t GAM)\n")
        L.append(md(pd.read_csv(tp), "{:.1f}") + "\n")

    fp = os.path.join(R, "forecastwx_metrics.csv")
    if os.path.exists(fp):
        L.append("## T7. Forecast-weather experiment (weeks with archived ECMWF forecasts, one week ahead)\n")
        fm = pd.read_csv(fp)
        fd = pd.read_csv(os.path.join(R, "forecastwx_dm.csv"))
        n = int(fm.groupby("site")["n"].first().iloc[0])
        L.append(f"{n} test weeks (archive starts March 2024). Models trained on reanalysis weather, tested on the forecast "
                 "that was available on the Sunday before the week. Air quality is last week's observed value.\n")
        t = fm.pivot(index="model", columns="site", values="MAE")[SITES].reset_index()
        L.append(md(t) + "\n")
        t = fm.pivot(index="model", columns="site", values="skill_vs_B2")[SITES] * 100
        L.append("Skill vs last week (%):\n")
        L.append(md(t.reset_index()) + "\n")
        rows = []
        for _, r in fd.iterrows():
            rows.append({"Comparison": f"{r.model_a} vs {r.model_b}", "Site": r.site, "MAE diff": f"{r.mean_abs_err_diff:+.1f}",
                         "p": pfmt(r.p_raw), "p (Holm)": pfmt(r.p_holm) if pd.notna(r.p_holm) else "n/a"})
        L.append(md(pd.DataFrame(rows)) + "\n")
    open(os.path.join(R, "results_tables.md"), "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
